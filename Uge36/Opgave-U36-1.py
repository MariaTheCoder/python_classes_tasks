# Beregn prisen på 3 biografbilletter

# Algoritme:

# 1) Spørg efter billetpris
billetpris = input("Hvad er prisen per biografbillet i DKK? ")

# 2) Konverter prisen til et tal
billetpris = int(billetpris)

# 3) Gang med 3
samlet_billetpris = billetpris * 3

# 4) Vis resultat
print("Den samlede billetpris bliver da", samlet_billetpris, "DKK.")